// The WebAssembly benchmark: Klar compiled to JavaScript vs Klar compiled to WebAssembly vs hand-written
// JavaScript, in Node and in a browser (Chromium through Playwright, when it is installed).
//
//   node bench/wasm/run.mjs            writes bench/wasm/RESULTS.md
//
// Needs Python 3 (the Klar compiler), clang + wasm-ld (for the WebAssembly module) and Node 22+.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import http from "node:http";
import os from "node:os";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..", "..");
const OUT = fs.mkdtempSync(path.join(os.tmpdir(), "klar-wasm-bench-"));
const klar = (...args) => execFileSync("python3", ["-m", "klar", ...args], { cwd: ROOT, env: { ...process.env, PYTHONPATH: ROOT }, stdio: ["ignore", "pipe", "inherit"] });

console.error("building bench.klar for Node and for the browser ...");
klar("build", "--target", "node", path.join(HERE, "bench.klar"), "-o", path.join(OUT, "bench.mjs"));
klar("build", "--target", "web", path.join(HERE, "bench.klar"), "-o", path.join(OUT, "bench.html"));
fs.copyFileSync(path.join(HERE, "kernels.js"), path.join(OUT, "kernels.js"));
fs.writeFileSync(path.join(OUT, "hand.html"), '<!doctype html><meta charset="utf-8"><script type="module">import { main } from "./kernels.js"; main();</script>');
const html = fs.readFileSync(path.join(OUT, "bench.html"), "utf8");
const wasmBytes = Math.round((/\$wasm_b64\("([A-Za-z0-9+/=]+)"\)/.exec(html)[1].length * 3) / 4);

const rows = [];          // [env, kernel, variant, run, ms, result]
const take = (env, text) => {
  for (const line of text.split("\n")) {
    const f = line.split("\t");
    if (f.length === 5) rows.push([env, f[0], f[1], +f[2], +f[3], f[4]]);
  }
};

console.error("running in Node ...");
take("Node", execFileSync("node", [path.join(OUT, "bench.mjs")], { maxBuffer: 1 << 26 }).toString());
take("Node", execFileSync("node", ["--input-type=module", "-e", `import { main } from ${JSON.stringify(path.join(OUT, "kernels.js"))}; main();`]).toString());

let browser = null;
try {
  const require = createRequire(import.meta.url);
  const { chromium } = require("playwright");
  const server = http.createServer((req, res) => {
    const file = path.join(OUT, decodeURIComponent(new URL(req.url, "http://x").pathname));
    if (!file.startsWith(OUT) || !fs.existsSync(file)) { res.writeHead(404); res.end(); return; }
    res.writeHead(200, { "content-type": file.endsWith(".js") ? "text/javascript" : "text/html" });
    res.end(fs.readFileSync(file));
  });
  await new Promise(r => server.listen(0, "127.0.0.1", r));
  const base = `http://127.0.0.1:${server.address().port}/`;
  const b = await chromium.launch();
  browser = `Chromium ${b.version()}`;
  console.error(`running in ${browser} ...`);
  for (const [page, lines] of [["bench.html", 60], ["hand.html", 30]]) {
    const p = await b.newPage();
    const got = [];
    const done = new Promise(resolve => p.on("console", m => { got.push(m.text()); if (got.length >= lines) resolve(); }));
    await p.goto(base + page);
    await Promise.race([done, new Promise((_, rej) => setTimeout(() => rej(new Error(`${page} timed out`)), 600_000))]);
    take("Chromium", got.join("\n"));
    await p.close();
  }
  await b.close();
  server.close();
} catch (e) {
  console.error(`skipping the browser run: ${e.message}`);
}

// ---------------------------------------------------------------- report
const envs = [...new Set(rows.map(r => r[0]))];
const kernels = [...new Set(rows.map(r => r[1]))];
const variants = ["Klar -> JS", "Klar -> wasm", "hand-written JS"];
const pick = (env, k, v) => rows.filter(r => r[0] === env && r[1] === k && r[2] === v);
const results = new Set();
for (const k of kernels) {
  const rs = new Set(rows.filter(r => r[1] === k).map(r => r[5]));
  if (rs.size !== 1) throw new Error(`${k}: results differ between variants: ${[...rs].join(" | ")}`);
  results.add(k);
}
const ms = x => `${x} ms`;
let md = `# Klar compiled to WebAssembly vs JavaScript

Generated by \`node bench/wasm/run.mjs\` on ${new Date().toISOString().slice(0, 10)}: ${os.cpus().length} CPUs, ${os.platform()}, Node ${process.version}${browser ? `, ${browser} (headless)` : ""}.

The same Klar source (\`kernels.klar\`) compiled two ways, called from one Klar app (\`bench.klar\`): with the
JavaScript backend (\`use kernels\`) and as WebAssembly (\`extern "wasm:kernels.<fn>"\`). "Hand-written JS" is
\`kernels.js\`: the same algorithms written the way a JavaScript developer would (typed arrays, in-place updates).
Every variant's result is checked to be identical. Times are milliseconds of computation inside the page or
process (Klar's \`time_millis\` / \`Date.now()\`), not counting start-up. **Warm** is the best of runs 2-5,
**cold** is run 1. The WebAssembly module (all six kernels plus the runtime) is ${(wasmBytes / 1024).toFixed(0)} KB.
`;
for (const env of envs) {
  md += `\n### ${env}\n\n| Kernel | Klar -> JS warm | Klar -> wasm warm | hand-written JS warm | wasm vs Klar -> JS | wasm vs hand-written | cold: JS / wasm / hand |\n|---|---|---|---|---|---|---|\n`;
  for (const k of kernels) {
    const w = {}, c = {};
    for (const v of variants) {
      const rs = pick(env, k, v);
      w[v] = Math.min(...rs.filter(r => r[3] > 1).map(r => r[4]));
      c[v] = rs.find(r => r[3] === 1)[4];
    }
    const sp = (a, b) => (a / b >= 1 ? `${(a / b).toFixed(1)}x faster` : `${(b / a).toFixed(1)}x slower`);
    md += `| ${k} | ${ms(w["Klar -> JS"])} | ${ms(w["Klar -> wasm"])} | ${ms(w["hand-written JS"])} | ${sp(w["Klar -> JS"], w["Klar -> wasm"])} | ${sp(w["hand-written JS"], w["Klar -> wasm"])} | ${c["Klar -> JS"]} / ${c["Klar -> wasm"]} / ${c["hand-written JS"]} |\n`;
  }
}
fs.writeFileSync(path.join(HERE, "RESULTS.md"), md);
fs.writeFileSync(path.join(HERE, "results.tsv"), rows.map(r => r.join("\t")).join("\n") + "\n");
console.log(md);
